import { Department } from './department';
import { ReportStatus, StatusHistoryEntry } from './status';
import { AIAnalysis, FakeSignals } from './ai';

/** Latitude/longitude pair, compatible with Leaflet's LatLng. */
export interface GeoLocation {
  lat: number;
  lng: number;
}

/**
 * A single citizen complaint stored in the `reports` Firestore collection.
 *
 * Firestore path: /reports/{reportId}
 *
 * One report maps to at most one incident. Multiple reports can share
 * an incident (duplicate/cluster detection links them).
 */
export interface Report {
  /** Firestore document ID, also shown to the citizen for tracking. */
  id: string;

  // ── Citizen-provided fields ────────────────────────────────────────

  /** Original complaint text (may be in English, Kannada, or Hindi). */
  text: string;
  /** Category selected by the citizen at submission time. */
  category: string;
  /** Pin location chosen on the map or via geolocation. */
  location: GeoLocation;
  /** Download URL from Firebase Storage, null if no photo attached. */
  imageUrl: string | null;

  // ── AI pipeline output (cached — never reprocessed) ────────────────

  /**
   * Full AI analysis result. Null until the pipeline runs.
   * Once set, the pipeline will skip this report (cache rule).
   */
  aiResult: AIAnalysis | null;
  /** True if aiResult came from the rule-based fallback, not Gemini. */
  fallbackMode: boolean;

  // ── Derived fields set by the pipeline ─────────────────────────────

  /** Detected language of the original text. */
  language: 'en' | 'kn' | 'hi' | 'unknown';
  /** Text translated to English (same as original if already English). */
  translatedText: string;
  /** AI-suggested department (may differ from category-based default). */
  department: Department | null;
  /** AI confidence in its analysis, 0-1. */
  confidence: number;

  // ── Fake/spam detection ────────────────────────────────────────────

  /** Composite suspicion score, 0-100. High → review queue. Never auto-reject. */
  fakeScore: number;
  /** Individual signal flags that contributed to fakeScore. */
  fakeSignals: FakeSignals;
  /** Human-readable reasons for the suspicion score. */
  fakeReasons: string[];
  /** Perceptual hash of the image for duplicate-image detection. Null if no image. */
  imageHash: string | null;

  // ── Incident linkage ───────────────────────────────────────────────

  /** ID of the parent incident this report was merged into. Null if unlinked. */
  incidentId: string | null;

  // ── Status & lifecycle ─────────────────────────────────────────────

  status: ReportStatus;
  /** Ordered timeline of status changes. */
  statusHistory: StatusHistoryEntry[];

  // ── Metadata ───────────────────────────────────────────────────────

  createdAt: string;   // ISO 8601
  updatedAt: string;   // ISO 8601
  /** True if this report was generated by the seed script. */
  synthetic: boolean;
}

