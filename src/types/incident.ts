import { Department } from './department';
import { IncidentStatus, StatusHistoryEntry } from './status';
import { PriorityFactors } from './ai';
import { GeoLocation } from './report';

/**
 * Verification status after an incident is marked "resolved".
 * - pending: waiting for citizen response
 * - verified: citizen confirmed the fix
 * - disputed: citizen said "not fixed" — incident should reopen
 */
export type VerificationStatus = 'pending' | 'verified' | 'disputed';

/**
 * An incident aggregates one or more related reports into a single
 * root-cause issue. Stored in the `incidents` Firestore collection.
 *
 * Firestore path: /incidents/{incidentId}
 *
 * "Incidents, not tickets" — the core abstraction of UrbanPulse.
 */
export interface Incident {
  /** Firestore document ID. */
  id: string;

  // ── Report aggregation ─────────────────────────────────────────────

  /** IDs of all reports that belong to this incident. */
  memberReportIds: string[];
  /** Count of linked reports. Denormalized for quick reads/sorting. */
  reportCount: number;

  // ── AI-generated summary ───────────────────────────────────────────

  /** Merged summary across all linked reports. */
  mergedSummary: string;
  /** AI's best guess at the root cause, if enough data. */
  rootCauseGuess: string | null;
  /** Reasons why member reports were clustered into this incident. */
  matchReasons?: string[];

  // ── Deterministic priority ─────────────────────────────────────────

  /**
   * Final priority score, 0-100.
   * Computed by a deterministic weighted sum — never by the LLM.
   * Higher = more urgent.
   */
  priorityScore: number;
  /** Per-factor breakdown so admins can see "why this score". */
  priorityFactors: PriorityFactors;

  // ── Department routing (labelled "simulated" in UI) ────────────────

  /** Primary department responsible. */
  leadDepartment: Department;
  /** Additional departments for cross-category incidents. May be empty. */
  supportingDepartments: Department[];
  /** Mocked field crew assigned to resolve this incident. */
  assignedCrew?: string | null;
  /** Explicit department assignment override by admin. */
  assignedDepartment?: Department | null;

  // ── Location ───────────────────────────────────────────────────────

  /** Centroid of all linked report locations. */
  location: GeoLocation;

  // ── Status & lifecycle ─────────────────────────────────────────────

  status: IncidentStatus;
  statusHistory: StatusHistoryEntry[];
  /**
   * Tracks citizen verification after resolution.
   * null until the incident reaches "resolved" status.
   */
  verificationStatus: VerificationStatus | null;
  /** True if a citizen disputed a previous resolution. */
  closureUnreliable: boolean;

  // ── Metadata ───────────────────────────────────────────────────────

  createdAt: string;   // ISO 8601
  updatedAt: string;   // ISO 8601
  /** True if this incident was generated by the seed script. */
  synthetic: boolean;
}

