import { Department } from './department';

/**
 * Strict JSON shape returned by the single Gemini call per report.
 * The prompt must instruct the model to return exactly this structure.
 * Validated server-side before use; falls back to rule-based analysis on failure.
 */
export interface AIAnalysis {
  /** Detected language of the original text. */
  language: 'en' | 'kn' | 'hi' | 'unknown';
  /** Report text translated to English (same as original if already English). */
  translatedText: string;
  /** AI-assigned category (may differ from citizen-selected one). */
  category: string;
  /** One-line summary of the complaint. */
  summary: string;
  /** Findings from the attached image, if any. */
  imageFindings: string | null;
  /** Severity cues extracted from text + image. */
  severityCues: string[];
  /** Suggested department for routing. */
  department: Department;
  /** Model's confidence in its analysis (0-1). */
  confidence: number;
  /**
   * True if the text and image seem to describe different things.
   * Feeds into the fake/spam suspicion score.
   */
  textImageMismatch: boolean;
}

/**
 * Signals used to compute the fake/spam suspicion score.
 * Each flag is independent; the score is a deterministic weighted sum.
 * High-scoring reports go to the review queue — never auto-rejected.
 */
export interface FakeSignals {
  /** AI flagged text-image mismatch. */
  textImageMismatch: boolean;
  /** Image has no recognizable outdoor/scene content. */
  noSceneInImage: boolean;
  /** Same user submitted many reports in a short window. */
  rapidRepeatSubmission: boolean;
  /** Text is gibberish or extremely short. */
  gibberishText: boolean;
  /** Report location is outside the Mysuru service area. */
  outOfServiceArea: boolean;
  /** Image hash matches a previously submitted report's image. */
  reusedImageHash: boolean;
}

/**
 * Breakdown of the deterministic priority score.
 * Each factor is normalized to 0-1 before the weighted sum.
 * Weights defined in the scoring function, not by the LLM.
 */
export interface PriorityFactors {
  /** Risk to life/safety from keywords + severity cues. Weight: 0.30 */
  safetyRisk: number;
  /** How many people are affected (report count in the incident). Weight: 0.20 */
  peopleAffected: number;
  /** Severity inferred from the image. Weight: 0.15 */
  imageSeverity: number;
  /** How old the earliest report is (older = higher urgency). Weight: 0.10 */
  age: number;
  /** Proximity to schools, hospitals, etc. Weight: 0.15 */
  sensitiveLocation: number;
  /** How many times this location has had similar issues. Weight: 0.10 */
  recurrenceHistory: number;
}

/**
 * Shape of the per-department AI morning brief.
 * Generated by Gemini, cached daily in Firestore.
 */
export interface MorningBrief {
  department: Department;
  /** ISO 8601 date string for the day this brief covers. */
  date: string;
  summary: string;
  topIssues: string[];
  trends: string[];
  /** True if this was generated by a rule-based fallback instead of Gemini. */
  fallbackMode: boolean;
}

